"""Writes app/src/main/assets/www/js/drills-data.js from research/drills.json (the drill collection).
Drill ids are permanent: results on the phone refer to them. Never renumber or reuse an id; add new drills with new ids."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'research', 'drills.json')
j = json.load(open(src, encoding='utf-8'))
keep = ['id', 'name', 'weapon', 'motion', 'timed', 'live', 'dry', 'level', 'distance', 'rounds', 'par', 'target', 'printable',
        'goal', 'steps', 'standard', 'dryNote', 'credit', 'aka', 'kw']
drills = [{k: d.get(k) for k in keep} for d in j['drills']]
out = os.path.join(HERE, '..', 'app', 'src', 'main', 'assets', 'www', 'js', 'drills-data.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Stoic Ranger - Shooting Drills — drill library (generated by tools/make_drills.py from research/drills.json, '
            + j['generated'] + '). Drill ids are permanent. */\n\'use strict\';\n')
    f.write('SD.DRILLS = ' + json.dumps(drills, ensure_ascii=False, separators=(',', ':')).replace('},{', '},\n{') + ';\n')
print(len(drills), 'drills ->', out)
