/* Makes www/js/quotes.js from SR Daily Thoughts' content.js: only what the dashboard needs (quote id, text, source,
   author) and the fixed day order, so the dashboard shows the same thought of the day as the phone.
   Usage: node tools/make-quotes.mjs <daily-thoughts www/js/content.js> */
import fs from 'fs'; import vm from 'vm';
const src = fs.readFileSync(process.argv[2], 'utf8'); const ctx = { DT: {} }; vm.runInNewContext(src, ctx);
const A = {}; ctx.DT.AUTHORS.forEach(a => A[a.slug] = a.name);
const Q = ctx.DT.QUOTES.map(q => [q.id, q.a, q.q.join(' '), q.ref]);
const out = `/* Generated by tools/make-quotes.mjs from SR Daily Thoughts content.js (${Q.length} quotes) - do not edit. Quote ids are permanent. */\n'use strict';\n` +
  `window.SRQ = { AUTHORS: ${JSON.stringify(A)},\n QUOTES: ${JSON.stringify(Q)},\n DAY_ORDER: ${JSON.stringify(ctx.DT.DAY_ORDER)} };\n`;
fs.writeFileSync(new URL('../www/js/quotes.js', import.meta.url), out); console.log(Q.length, 'quotes,', ctx.DT.DAY_ORDER.length, 'in day order');
