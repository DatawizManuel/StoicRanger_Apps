// Writes www/sr/drill-names.js (drill id → name) from www/drills/js/drills-data.js, for the Training Log part,
// which shows drill results by name. Run after every change of the drill library: node tools/make-drill-names.js
const fs = require('fs'), path = require('path');
const WWW = path.join(__dirname, '..', 'app', 'src', 'main', 'assets', 'www');
const SD = {};
new Function('SD', fs.readFileSync(path.join(WWW, 'drills/js/drills-data.js'), 'utf8'))(SD);
const names = Object.fromEntries(SD.DRILLS.map(d => [d.id, d.name]));
fs.writeFileSync(path.join(WWW, 'sr/drill-names.js'), '/* Generated by tools/make-drill-names.js — drill id → name for the Training Log part. */\nwindow.SR_DRILL_NAMES = ' + JSON.stringify(names) + ';\n');
console.log(Object.keys(names).length + ' drill names written');
